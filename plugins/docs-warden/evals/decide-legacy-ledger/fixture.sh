#!/usr/bin/env bash
# The it-tooling fixture as a 0.x project left it: one accepted record, the
# generated index, and the CONVENTIONS and README lines that pointed at them.
# Without the plugin, the obvious move is to add DEC-0002 beside DEC-0001.
. "$(dirname "$0")/../_lib/seed.sh"
seed repo-it-tooling

mkdir -p docs/decisions
cat > docs/decisions/DEC-0001-preview-every-certificate-rotation-before-running-it.md <<'EOF'
---
id: DEC-0001
title: Preview every certificate rotation before running it
status: accepted
date: 2026-09-01
deciders: [it-team]
supersedes: []
tags: []
---

# DEC-0001: Preview every certificate rotation before running it

## Context and problem statement

A rotation run against the wrong hub replaced a live certificate.

## Considered options

1. **Always run with -WhatIf first** -- shows every change before it happens.
2. **Trust the hub name** -- faster, and how the wrong hub was hit.

## Decision outcome

Chose **always run with -WhatIf first**, because a preview costs a minute and a
wrong rotation costs an outage.
EOF

cat > docs/DECISIONS.md <<'EOF'
<!-- GENERATED by docs-warden - do not edit -->

# Decisions

Why this repository is the way it is. Newest first.

| ID | Title | Status | Date | Supersedes | Superseded by |
|----|-------|--------|------|------------|---------------|
| [DEC-0001](decisions/DEC-0001-preview-every-certificate-rotation-before-running-it.md) | Preview every certificate rotation before running it | accepted | 2026-09-01 | - | - |

To add a decision, run `adr_new.py <repo> "<title>"`, fill the sections with
the deciders, then re-run `adr_index.py`. Accepted records are never edited --
reverse one by writing a new record with `supersedes: [DEC-NNNN]`.
EOF

sed -i 's/^The reason for a rule sits next to the rule\.$/Accepted decision records are never edited; supersede them instead./' docs/CONVENTIONS.md
sed -i 's#^| \[CONVENTIONS.md\](docs/CONVENTIONS.md) | How we do things here today |$#&\n| [DECISIONS.md](docs/DECISIONS.md) | Why we do them that way |#' README.md

